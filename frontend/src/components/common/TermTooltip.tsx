import React, { useState } from 'react';
import { Info } from 'lucide-react';

export const BUSINESS_GLOSSARY: Record<string, string> = {
  revenue: 'Total money generated by sales or services before subtracting any costs or expenses.',
  profit: 'Net money remaining after all operational, product, and overhead expenses are deducted.',
  profit_margin: 'The percentage of revenue turned into profit (Profit ÷ Revenue × 100). Higher is better.',
  growth_rate: 'The percentage change in revenue or transactions compared to a previous period.',
  correlation: 'Shows whether two variables tend to change together. It does not prove causation.',
  outlier: 'An unusually high or low transaction or value that differs significantly from normal patterns.',
  contribution: 'The portion of an overall change (drop or increase) accounted for by a specific segment.',
  priority: 'Calculated urgency score (0–100) based on estimated financial gain, evidence strength, and implementation ease.',
  what_if: 'Simulation showing projected revenue and profit when business levers like price or discount are adjusted.'
};

interface Props {
  termKey?: keyof typeof BUSINESS_GLOSSARY | string;
  label?: string;
  definition?: string;
  children?: React.ReactNode;
}

export const TermTooltip: React.FC<Props> = ({ termKey, label, definition, children }) => {
  const [isOpen, setIsOpen] = useState(false);

  const text = definition || (termKey ? BUSINESS_GLOSSARY[termKey.toLowerCase()] : '') || '';
  const displayLabel = label || children;

  return (
    <span
      className="relative inline-flex items-center gap-1 group cursor-help"
      onMouseEnter={() => setIsOpen(true)}
      onMouseLeave={() => setIsOpen(false)}
      onClick={() => setIsOpen(!isOpen)}
    >
      <span className="underline decoration-dotted decoration-slate-400 underline-offset-2">
        {displayLabel}
      </span>
      <Info className="w-3.5 h-3.5 text-slate-400 group-hover:text-blue-600 transition-colors shrink-0" />

      {isOpen && text && (
        <span className="absolute bottom-full left-1/2 -translate-x-1/2 mb-2 w-64 p-2.5 bg-slate-900 text-white text-[11px] leading-relaxed rounded-lg shadow-xl z-50 pointer-events-none text-left">
          {text}
          <span className="absolute top-full left-1/2 -translate-x-1/2 -mt-1 border-4 border-transparent border-t-slate-900" />
        </span>
      )}
    </span>
  );
};
